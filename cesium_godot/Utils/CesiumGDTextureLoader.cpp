#include "CesiumGDTextureLoader.h"
#include "CesiumGltf/ImageAsset.h"
#include "godot_cpp/core/error_macros.hpp"
#include "error_names.hpp"

constexpr int32_t RGBA_CHANNEL_COUNT = 4;
constexpr int32_t RGB_CHANNEL_COUNT = 3;

Ref<ImageTexture> CesiumGDTextureLoader::load_image_texture(const CesiumGltf::ImageAsset& image, bool generateMipMaps, bool imageHasMipMaps)
{
	Ref<Image> godotImage = load_image(image, generateMipMaps, imageHasMipMaps);
	if (godotImage.is_null()) {
		return Ref<ImageTexture>();
	}
	return ImageTexture::create_from_image(godotImage);
}

Ref<Image> CesiumGDTextureLoader::load_image(const CesiumGltf::ImageAsset& image, bool generateMipMaps, bool imageHasMipMaps)
{
	//TODO: we can probably optimize this
	PackedByteArray rawImageData;
	size_t pixelSize = image.pixelData.size();

	for (size_t i = 0; i < pixelSize; ++i)
	{
		const std::byte& element = image.pixelData.at(i);
		rawImageData.push_back(static_cast<uint8_t>(element));
	}

	Image::Format cesiumFormat;
	Error err = try_get_image_format(image.channels, image.bytesPerChannel, &cesiumFormat);
	ERR_FAIL_COND_V_MSG(err != Error::OK, Ref<Image>(), "Image format not recognized!");

	// THE DATA SAYS WHETHER IT CARRIES A MIP CHAIN, NOT THE CALLER. 29 Oct 2026 04:0x, Mai World streaming Google's
	// tiles at Kailasa: Godot's "Data for slice index 0 ... differs in size (supplied: 262144) than what is
	// required by the format (349524)" (a 256x256 RGBA8 base image handed over as if it held its mips, x 4/3),
	// then "texture.rd_texture.is_null()" and heap corruption (0xC0000374) in the upload. The raster path says
	// `imageHasMipMaps = true` after asking cesium-native to generate them, but the asset's pixelData holds a
	// chain only when its mipPositions say so (cesium-native ImageAsset.h: "If this is empty, assume the entire
	// buffer is a single image, the mip map will need to be generated on the client in this case"; "If
	// mipPositions is not empty, this buffer will contains multiple mips back-to-back"). So the flag is read off
	// the asset and checked against the byte count a chain needs; a buffer that does not hold the chain is
	// uploaded as the base image, and mips are generated by Godot instead.
	const size_t bytesPerPixel = static_cast<size_t>(image.channels) * static_cast<size_t>(image.bytesPerChannel);
	const size_t baseBytes = static_cast<size_t>(image.width) * static_cast<size_t>(image.height) * bytesPerPixel;
	size_t chainBytes = 0;
	for (int32_t w = image.width, h = image.height;; w = (w > 1 ? w / 2 : 1), h = (h > 1 ? h / 2 : 1)) {
		chainBytes += static_cast<size_t>(w) * static_cast<size_t>(h) * bytesPerPixel;
		if (w == 1 && h == 1) break;
	}
	const bool dataHasMipMaps = imageHasMipMaps && image.mipPositions.size() > 1 && pixelSize == chainBytes;
	if (imageHasMipMaps && !dataHasMipMaps) {
		generateMipMaps = generateMipMaps || pixelSize == baseBytes;
	}
	ERR_FAIL_COND_V_MSG(pixelSize != baseBytes && pixelSize != chainBytes, Ref<Image>(),
		"Cesium image byte count matches neither its base image nor a full mip chain - not uploaded");

	Ref<Image> godotImage = Image::create_from_data(
		image.width,
		image.height,
		dataHasMipMaps,
		cesiumFormat,
		rawImageData
	);

	if (generateMipMaps && !dataHasMipMaps) {
		err = godotImage->generate_mipmaps();

		if (err != Error::OK) {
			ERR_PRINT(String("Mipmaps were not generated! Error: ") + REFLECT_ERR_NAME(err));
		}

	}
	return godotImage;
}

Error CesiumGDTextureLoader::try_get_image_format(int32_t channelCount, int32_t bytesPerChannel, Image::Format* outFormat)
{
	bool isRGB = channelCount == RGB_CHANNEL_COUNT;
	bool isRGBA = channelCount == RGBA_CHANNEL_COUNT;
	ERR_FAIL_COND_V_MSG(
		!isRGB && !isRGBA,
		Error::ERR_FILE_CORRUPT,
		"Cesium image does not conform to RGB or RGBA color space"
	);

	constexpr int32_t SINGLE_BYTE_PER_CHANNEL = 1;
	constexpr int32_t FLOATING_POINT_BYTES_PER_CHANNEL = 4;

	switch (bytesPerChannel) {
	case SINGLE_BYTE_PER_CHANNEL:
		*outFormat = isRGBA ? Image::FORMAT_RGBA8 : Image::FORMAT_RGB8;
		break;
	case FLOATING_POINT_BYTES_PER_CHANNEL:
		*outFormat = isRGBA ? Image::FORMAT_RGBAF : Image::FORMAT_RGBF;
		break;
	}
	return Error::OK;
}
